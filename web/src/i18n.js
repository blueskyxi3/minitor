export function translator(language) {
  const normalized = String(language || 'en').replace('-', '_').toLowerCase();
  const index = normalized.startsWith('zh') ? (/hk|tw|hant/.test(normalized) ? 1 : 0) : normalized.startsWith('ja') ? 3 : 2;
  return (key) => messages[key]?.[index] || key.replace(/^stage_/, '');
}
